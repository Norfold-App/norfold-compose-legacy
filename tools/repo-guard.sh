#!/usr/bin/env bash
# Norfold repository guard.
#
# Rejects the specific mistakes that agent sessions have actually made: attribution
# markers, machine-local paths, agent scratch files, build output, and credentials.
# The rules themselves are in AGENTS.md; this only enforces the mechanical subset.
#
#   tools/repo-guard.sh              check what is staged (use before committing)
#   tools/repo-guard.sh --install    install as .git/hooks/pre-commit
#   tools/repo-guard.sh --range A..B check a commit range (used by CI)
#
# Exit 0 clean, 1 violations found.

set -uo pipefail
cd "$(git rev-parse --show-toplevel)" || exit 1

if [ "${1:-}" = "--install" ]; then
    hook=".git/hooks/pre-commit"
    printf '#!/usr/bin/env bash\nexec tools/repo-guard.sh\n' > "$hook"
    chmod +x "$hook"
    echo "installed $hook"
    exit 0
fi

fail=0
note() { printf '  %s\n' "$1"; }
violation() { printf '\nREJECTED: %s\n' "$1"; fail=1; }

# ---- which files, and which commit messages, are we judging? --------------------------
if [ "${1:-}" = "--range" ]; then
    range="${2:?--range needs A..B}"
    files=$(git diff --name-only --diff-filter=ACMR "$range")
    messages=$(git log --format='%B%n%an <%ae>' "$range")
    blob() { git show "$range_end:$1" 2>/dev/null; }
    range_end="${range##*..}"
else
    files=$(git diff --cached --name-only --diff-filter=ACMR)
    messages=$(git var GIT_AUTHOR_IDENT)
    blob() { git show ":$1" 2>/dev/null; }
fi

[ -z "$files" ] && { echo "repo-guard: nothing to check"; exit 0; }

# This script's own pattern definitions necessarily contain the strings it rejects, so it is
# exempt from the content scans below. It is still subject to the filename rules. The rules
# document (AGENTS.md) has the same self-referential exemptions: its own rule examples are
# exactly the literals the scan looks for.
scannable() {
    case "$1" in
        tools/repo-guard.sh|AGENTS.md) return 1 ;;
        *) return 0 ;;
    esac
}

# ---- 1. attribution markers ----------------------------------------------------------
# Committed source and commit messages carry the owner and nothing else.
attrib="Co-[Aa]uthored-[Bb]y|[Gg]enerated with|generated by (Claude|Codex|GPT|Copilot|Cursor|Gemini)|🤖"
if printf '%s' "$messages" | grep -qE "$attrib"; then
    violation "commit message carries an attribution marker"
    printf '%s' "$messages" | grep -nEi "$attrib" | head -5 | while read -r l; do note "$l"; done
fi
for f in $files; do
    scannable "$f" || continue
    if blob "$f" | grep -qE "$attrib"; then
        violation "$f carries an attribution marker"
        blob "$f" | grep -nE "$attrib" | head -3 | while read -r l; do note "$l"; done
    fi
done

# ---- 2. machine-local paths ----------------------------------------------------------
# A path that only resolves on one machine is broken for everyone else. Documented
# build commands legitimately reference the pinned JDK, so that one form is allowed.
localpath="/home/[a-z]|C:\\\\\\\\Users|wsl\\.localhost|/Users/[a-z]|/mnt/c/Users"
for f in $files; do
    scannable "$f" || continue
    hits=$(blob "$f" | grep -nE "$localpath" | grep -v 'gradle/jdks/eclipse_adoptium' | head -3)
    if [ -n "$hits" ]; then
        violation "$f contains a machine-local path"
        printf '%s\n' "$hits" | while read -r l; do note "$l"; done
    fi
done

# ---- 3. files that must never be committed -------------------------------------------
for f in $files; do
    case "$f" in
        *:Zone.Identifier|*.jks|*.keystore|*.p12|*.pem|*id_rsa*|*service-account*.json)
            violation "$f must never be committed" ;;
        codex-handoffs/*|graphify-out/*|*/agent-transcripts/*|.serena/*|.claude/*)
            violation "$f is agent scratch material" ;;
        apps/android/build/*|*/node_modules/*|dist/*|*.apk|*.aab|classes.jar)
            violation "$f is generated build output" ;;
        .env|.env.*|*/.env)
            violation "$f may carry credentials" ;;
    esac
done

# ---- 4. credential-shaped literals ---------------------------------------------------
# Long opaque tokens and provider key prefixes. Shape-based, so it is deliberately
# narrow: it catches pasted real keys, not placeholders.
secrets='(sk-[A-Za-z0-9]{20,}|ghp_[A-Za-z0-9]{20,}|eyJ[A-Za-z0-9_-]{30,}\.[A-Za-z0-9_-]{20,}|AKIA[0-9A-Z]{16}|-----BEGIN [A-Z ]*PRIVATE KEY-----)'
for f in $files; do
    scannable "$f" || continue
    case "$f" in *.md|*.txt) continue ;; esac
    if blob "$f" | grep -qE "$secrets"; then
        violation "$f contains a credential-shaped literal"
        note "$(blob "$f" | grep -nEo "$secrets" | head -2 | cut -c1-60)"
    fi
done

# ---- 5. editor feature flags stay false ----------------------------------------------
flags="apps/android/src/main/java/com/norfold/app/editor/flags/EditorFeatureFlags.kt"
if printf '%s\n' $files | grep -qx "$flags"; then
    if blob "$flags" | grep -E '(FLOW_HOST|DOCUMENT_HOST|SPREADSHEET_HOST)' | grep -q 'true'; then
        violation "$flags enables a host flag by default"
        note "every editor feature flag ships false; see AGENTS.md"
    fi
fi

if [ "$fail" -ne 0 ]; then
    printf '\nThe rules are in AGENTS.md. Fix the above rather than bypassing this check.\n'
    exit 1
fi
echo "repo-guard: clean ($(printf '%s\n' $files | wc -l) files)"
